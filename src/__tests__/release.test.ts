import * as fs from 'fs';
import * as path from 'path';
import { ECHO_CONFIG } from '../constants/gameConfig';

const ROOT = path.join(__dirname, '..', '..');
const read = (...p: string[]) => fs.readFileSync(path.join(ROOT, ...p), 'utf8');
const app = JSON.parse(read('app.json')).expo;
const pkg = JSON.parse(read('package.json'));

/** Width and height of a PNG from its header (and a check that it is a PNG at all). */
function pngSize(file: string): { w: number; h: number } {
  const b = fs.readFileSync(path.join(ROOT, file));
  expect([...b.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10]);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

describe('release configuration', () => {
  it('has a proper version everywhere, and the screens show the real one', () => {
    expect(app.version).toMatch(/^\d+\.\d+\.\d+$/);
    expect(pkg.version).toBe(app.version);
    expect(Number.isInteger(app.android.versionCode)).toBe(true);
    expect(app.android.versionCode).toBeGreaterThanOrEqual(1);
    expect(typeof app.ios.buildNumber).toBe('string');
    expect(read('src', 'screens', 'HomeScreen.tsx')).toContain('{appConfig.expo.version}');
  });

  it('has the same app id on both platforms and a name', () => {
    expect(app.android.package).toBe(app.ios.bundleIdentifier);
    expect(app.android.package).toMatch(/^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$/);
    expect(app.name.length).toBeGreaterThan(2);
    expect(app.orientation).toBe('portrait');
  });

  it('has real icon and splash images of the right size', () => {
    expect(pngSize(app.icon.replace('./', ''))).toEqual({ w: 1024, h: 1024 });
    expect(pngSize(app.android.adaptiveIcon.foregroundImage.replace('./', ''))).toEqual({ w: 1024, h: 1024 });
    expect(pngSize(app.splash.image.replace('./', ''))).toEqual({ w: 512, h: 512 });
    expect(pngSize(app.web.favicon.replace('./', ''))).toEqual({ w: 48, h: 48 });
    expect(app.android.adaptiveIcon.backgroundColor).toBe('#040711');
  });

  it('asks for no permissions an audio game does not need (no microphone, no overlay, no storage, no background service)', () => {
    const blocked: string[] = app.android.blockedPermissions;
    for (const p of ['RECORD_AUDIO', 'SYSTEM_ALERT_WINDOW', 'READ_EXTERNAL_STORAGE', 'WRITE_EXTERNAL_STORAGE', 'FOREGROUND_SERVICE', 'FOREGROUND_SERVICE_MEDIA_PLAYBACK']) {
      expect(blocked).toContain(`android.permission.${p}`);
    }
    // what the game does need is never blocked
    for (const p of ['INTERNET', 'VIBRATE', 'ACCESS_NETWORK_STATE']) expect(blocked).not.toContain(`android.permission.${p}`);
  });

  it('the audio plugin has the microphone and background playback switched off', () => {
    const entry = app.plugins.find((p: unknown) => Array.isArray(p) && p[0] === 'expo-audio');
    expect(entry).toBeTruthy();
    expect(entry[1]).toEqual({ microphonePermission: false, recordAudioAndroid: false, enableBackgroundRecording: false, enableBackgroundPlayback: false });
  });

  it('declares that it uses no non-exempt encryption (no export-compliance prompt)', () => {
    expect(app.ios.infoPlist.ITSAppUsesNonExemptEncryption).toBe(false);
  });

  it('the generated Android manifest, when present, matches (no stray permissions)', () => {
    const manifest = path.join(ROOT, 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
    if (!fs.existsSync(manifest)) return; // android/ is generated and not committed
    // entries marked tools:node="remove" are the removal markers (the permission is stripped from the final app)
    const xml = fs
      .readFileSync(manifest, 'utf8')
      .split('\n')
      .filter((line) => !line.includes('tools:node="remove"'))
      .join('\n');
    // the native project is regenerated by `expo prebuild`; if it is stale this test says so
    for (const p of ['RECORD_AUDIO', 'SYSTEM_ALERT_WINDOW', 'READ_EXTERNAL_STORAGE', 'WRITE_EXTERNAL_STORAGE', 'FOREGROUND_SERVICE']) expect(xml).not.toContain(`android.permission.${p}`);
    expect(xml).not.toContain('AudioControlsService'); // no background playback service
  });
});

describe('what ships switched on or off', () => {
  it('all online features are OFF until a backend address exists', () => {
    const o = ECHO_CONFIG.online;
    expect(o.cloudSave.enabled).toBe(false);
    expect(o.leaderboard.enabled).toBe(false);
    expect(o.ads.enabled).toBe(false);
  });

  it('a feature can only be enabled together with its address (never "on" with nowhere to go)', () => {
    const o = ECHO_CONFIG.online;
    if (o.cloudSave.enabled) expect(o.cloudSave.baseUrl).toMatch(/^https:\/\//);
    if (o.leaderboard.enabled) expect(o.leaderboard.baseUrl).toMatch(/^https:\/\//);
    for (const s of ECHO_CONFIG.trustedTime.sources) expect(s.url).toMatch(/^https:\/\//); // never plain http
  });

  it('debug tooling is gated on the development flag, so release builds have none', () => {
    const flags = read('src', 'debug', 'debugFlags.ts');
    expect(flags).toMatch(/DEBUG_ENABLED[^\n]*__DEV__/);
    const home = read('src', 'screens', 'HomeScreen.tsx');
    expect(home).toMatch(/if \(!DEBUG_ENABLED\) return/);
    expect(home).toMatch(/DEBUG_ENABLED && devPanelOpen/);
  });

  it('analytics are only printed to the console in development builds', () => {
    expect(read('src', 'analytics', 'Analytics.ts')).toMatch(/__DEV__[^\n]*\n\s*Analytics\.addSink\(\(e\) => console\.log/);
  });

  it('no source file leaves a debugger statement or a test-only shortcut in the game code', () => {
    const files: string[] = [];
    const walk = (dir: string) => {
      for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        if (e.name === '__tests__') continue;
        const p = path.join(dir, e.name);
        if (e.isDirectory()) walk(p);
        else if (/\.(ts|tsx)$/.test(e.name)) files.push(p);
      }
    };
    walk(path.join(ROOT, 'src'));
    for (const f of files) {
      const text = fs.readFileSync(f, 'utf8');
      expect({ f: path.relative(ROOT, f), debugger: /\bdebugger\s*;/.test(text) }).toEqual({ f: path.relative(ROOT, f), debugger: false });
    }
  });

  it('every dependency is pinned to a real version range (no "latest", no git urls)', () => {
    for (const [name, range] of Object.entries({ ...pkg.dependencies, ...pkg.devDependencies }) as [string, string][]) {
      expect({ name, ok: /^[~^]?\d/.test(range) }).toEqual({ name, ok: true });
    }
  });
});
