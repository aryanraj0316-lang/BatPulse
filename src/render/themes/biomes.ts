/**
 * BIOMES — every 10 levels the maze moves to a new place. Gameplay is identical;
 * only the art changes: palette, floor + wall details, light fixtures, atmosphere
 * particles, screen-edge ambience and the darkness tint.
 */

export type BiomeId = 'crypt' | 'grotto' | 'forge' | 'frost' | 'fungal' | 'astral';
export type LightKind = 'lantern' | 'jelly' | 'brazier' | 'icelamp' | 'shroom' | 'orb';
export type AtmosKind = 'motes' | 'bubbles' | 'embers' | 'snow' | 'spores' | 'stars';

type ThemePatch = Partial<{ [K in keyof typeof THEME]: (typeof THEME)[K] }>;
