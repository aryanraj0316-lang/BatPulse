/** Which biome a level belongs to: 10 levels each, cycling after the campaign. */
export function biomeForLevel(levelId: number): Biome {
  const i = Math.floor((Math.max(1, levelId) - 1) / CHAPTER_SIZE) % BIOMES.length;
  return BIOMES[i];
}

/** First level of the chapter this level is in. */
export function chapterStart(levelId: number) {
  return Math.floor((Math.max(1, levelId) - 1) / CHAPTER_SIZE) * CHAPTER_SIZE + 1;
}

